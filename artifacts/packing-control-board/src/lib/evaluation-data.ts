function normalize(row: EvaluationSourceRow): Order {
  const team: Team = row.pool.toUpperCase() === 'SYSTEM' ? 'SYSTEM' : 'PARTS';

  return {
    id: row.salesOrder,
    team,
    salesOrder: row.salesOrder,
    isRetailOrder: row.retail.toLowerCase() === 'yes',
    customer: row.customerName,
    productDescription: team === 'PARTS' ? row.machineType : '',
    machineModel: team === 'SYSTEM' ? row.machineType : '',
    confirmedShipDate: row.confirmedShipDate,
    requestedShipDate: row.requestedShipDate,
    customerPO: row.customerPO,
    modeOfDelivery: row.modeOfDelivery,
    incoterms: row.deliveryTerms,
    namedPlace: row.namedPlace,
    carrierForwarder: row.carrierForwarder,
    carrierForwarderDescription: row.carrierForwarder,
    customerCarrierAccount: row.custCarrierAccount,
    shippingInstructions: '',
    freightInformation: '',
    documentStatus: row.documentStatus,
    salesperson: row.salesperson,
    country: row.country,
    deliveryCity: row.namedPlace.split(',')[0]?.trim() ?? '',
    deliveryState: row.namedPlace.split(',')[1]?.trim().split(' ')[0] ?? '',
    customerReference: row.customerReference,
    createdDate: row.createdDateAndTime.replace(' ', 'T'),
    inPackingAt: row.createdDateAndTime.replace(' ', 'T'),
    doNotProcess: row.doNotProcess.toLowerCase() === 'yes',
    doNotProcessKnown: true,
    packStartedAt: null,
    priority: null,
  };
}

export const evaluationOrders: Order[] = sourceRows
  .filter((row) => row.inPacking.toLowerCase() === 'yes')
  .map(normalize);